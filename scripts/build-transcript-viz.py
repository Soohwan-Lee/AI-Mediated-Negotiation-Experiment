def render_trace(rows, L):
    if not rows:
        return ""
    out = ['<div class="trace">']
    for r in rows:
        k = r["kind"]
        head = r[f"{L}_head"]
        out.append(f'<div class="trace__row trace__row--{k}">')
        idtxt = f' <span style="font-family:\'IBM Plex Mono\',monospace;opacity:.65">{html.escape(r["id"])}</span>' if r.get("id") else ""
        out.append(f'<div class="trace__head">{head}{idtxt}</div>')
        if r.get(f"{L}_src"):
            out.append(f'<p class="trace__src">{r[f"{L}_src"]}</p>')
        out.append(f'<p class="trace__op">{r[f"{L}_op"]}</p>')
        if r.get("moves"):
            moves = MOVES_EN if L == "en" else MOVES_KO
            h = MOVES_HEAD_EN if L == "en" else MOVES_HEAD_KO
            cap = MOVES_CAP_EN if L == "en" else MOVES_CAP_KO
            out.append('<div class="tablewrap"><table class="moves"><thead><tr>'
                       f'<th>{h[0]}</th><th>{h[1]}</th></tr></thead><tbody>')
            for a, b in moves:
                out.append(f"<tr><td>{a}</td><td>{b}</td></tr>")
            out.append("</tbody></table></div>")
            out.append(f'<p class="trace__op" style="margin-top:.6rem">{cap}</p>')
        out.append("</div>")
    out.append("</div>")
    return "".join(out)


def render_turns(turns, L):
    out = []
    for t in turns:
        cls = "turn turn--you" if t["you"] else "turn"
        who = t["who"][0] if L == "en" else t["who"][1]
        stage_label = ("stage " if L == "en" else "") + t["stage"] if t["stage"] else ""
        if L == "ko" and t["stage"]:
            stage_label = t["stage"] + "단계"
        out.append(f'<article class="{cls}">')
        out.append(f'<div class="turn__stage">{stage_label}</div>')
        out.append("<div>")
        out.append(f'<p class="turn__speaker">{html.escape(who)}</p>')
        out.append(f'<p class="turn__text">{t[L]}</p>')
        out.append(render_trace(t["trace"], L))
        out.append("</div></article>")
    return "".join(out)


