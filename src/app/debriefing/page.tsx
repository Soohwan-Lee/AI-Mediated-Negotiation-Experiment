"use client";

/**
 * Debriefing (Methods §9).
 *
 * Full disclosure of the deception, before the completion code is issued:
 *  - the counterpart was a researcher-controlled LLM, not another participant
 *  - the counterpart's assistant was likewise part of the study protocol
 *  - the reward decision was scenario-only and changed nobody's payment
 *  - why this could not be disclosed up front
 *
 * The completion code is on the NEXT page and is issued unconditionally.
 *
 * NOTE: there is deliberately no post-debriefing data-withdrawal option here.
 * Confirm that against the approved protocol before recruitment — an IRB
 * reviewing a deception study often requires one.
 */

import { useRouter } from "next/navigation";
import { useState } from "react";
import { ActionBar } from "@/components/study-chrome";
import {
  Callout,
  Card,
  CardTitle,
  Checkbox,
  Field,
  Page,
  PageHeader,
  TextArea,
} from "@/components/ui";
import { useDevAutofill, useDevGate } from "@/lib/dev-mode";
import { useParticipant, usePageEnter } from "@/lib/participant-context";
import { STUDY, nextHref } from "@/lib/study-config";

export default function DebriefingPage() {
  usePageEnter("debriefing");
  const router = useRouter();
  const { assignment, saveResponses, logEvent } = useParticipant();
  const [acknowledged, setAcknowledged] = useState(false);
  const [comments, setComments] = useState("");
  const [busy, setBusy] = useState(false);

  const isMember = assignment?.role === "member";

  useDevAutofill(() => setAcknowledged(true));

  const canContinue = useDevGate(acknowledged);

  async function handleFinish() {
    if (!canContinue) return;
    setBusy(true);
    try {
      await saveResponses("debriefing", { acknowledged, comments });
      logEvent("debriefing_acknowledged");
      router.push(nextHref("debriefing"));
    } finally {
      setBusy(false);
    }
  }

  return (
    <>
      <Page>
        <PageHeader
          eyebrow="Debriefing"
          title="What this study was really about"
          subtitle="Thank you for taking part. Now that you have finished, here is the full picture."
        />

        <div className="mb-6">
          <Callout title="Please read this carefully" tone="warning">
            <p>
              Some parts of this study were not described accurately at the
              start. This was necessary for the research question, and it was
              reviewed and approved by our Institutional Review Board.
              Everything is explained below.
            </p>
          </Callout>
        </div>

        <div className="prose-study mb-8">
          <h2>The other party was not another participant</h2>
          <p>
            You were told you were negotiating with another person taking part
            in the study. In fact, <strong>there was no other participant</strong>
            . The counterpart&apos;s messages were generated by a
            researcher-controlled AI system following a fixed set of priorities
            and concession rules, identical for everyone.
          </p>
          <p>
            In the session where assistants negotiated, the
            &ldquo;counterpart&apos;s assistant&rdquo; was likewise part of the
            study system, not a tool belonging to a real person.
          </p>

          <h2>The reward decision was part of the scenario only</h2>
          {isMember ? (
            <p>
              You were shown a reward decision presented as the Project
              Leader&apos;s judgment of your contribution.{" "}
              <strong>
                That decision was not made by any person, and it did not depend
                on anything you did.
              </strong>{" "}
              Everyone in your role saw the same number. It has no effect
              whatsoever on your payment — you will receive the full amount
              advertised on Prolific, exactly as described in the consent form.
            </p>
          ) : (
            <p>
              You were asked to make a reward decision about the other party.
              Because there was no other participant,{" "}
              <strong>your decision did not affect anyone&apos;s payment.</strong>{" "}
              It was recorded only as data about how people use authority in
              this kind of scenario. Your own payment is unaffected.
            </p>
          )}

          <h2>Why we could not tell you in advance</h2>
          <p>
            This study looks at how people raise requirements that are
            legitimate but awkward to say out loud, and whether having an AI
            assistant negotiate for them changes that. It depends on you
            genuinely expecting a real person to read what was said and form an
            impression of you. Had you known the counterpart was a system, that
            expectation would disappear, and so would the behaviour we study.
          </p>
          <p>
            A controlled counterpart also means everyone faced the same
            negotiating partner, so differences between people reflect the study
            conditions rather than who they happened to be paired with.
          </p>

          <h2>If any of this troubles you</h2>
          <p>
            Some people find it uncomfortable to learn that an interaction was
            simulated, or to think back on a reward decision that felt real at
            the time. That reaction is understandable. If you feel any distress
            about taking part, please contact the research team at{" "}
            {STUDY.irb.researcherEmail}. You can also contact{" "}
            {STUDY.irb.institution}&apos;s Institutional Review Board at{" "}
            {STUDY.irb.contactEmail} (protocol {STUDY.irb.protocolNumber}) about
            your rights as a research participant.
          </p>
          <p>
            We ask that you not share these details with other Prolific workers,
            since the study depends on people not knowing them in advance.
          </p>
        </div>

        <Card>
          <CardTitle>Before you finish</CardTitle>

          <Checkbox checked={acknowledged} onChange={setAcknowledged}>
            I have read and understood this explanation.
          </Checkbox>

          <div className="mt-6">
            <Field label="Anything you would like to tell the research team?">
              <TextArea
                value={comments}
                onChange={setComments}
                rows={3}
                placeholder="Optional."
              />
            </Field>
          </div>
        </Card>
      </Page>

      <ActionBar
        label="Continue"
        onClick={handleFinish}
        disabled={!canContinue}
        busy={busy}
        note={
          acknowledged ? "Next: your completion code" : "Please confirm you have read this."
        }
      />
    </>
  );
}
